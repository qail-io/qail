const SNIPPET_TOKENS = 200;
/** Hard cap on a single full-content chunk, so one huge page cannot blow the reply. */
const MAX_FULL_CHARS = 12000;

function locationOf(chunk: Chunk): string {
    const heading = chunk.headingPath && chunk.headingPath.length
        ? " > " + chunk.headingPath.join(" > ")
        : "";
    return chunk.path + heading;
}

/**
 * A window of roughly SNIPPET_TOKENS whitespace-separated words centred on the
 * first query-term hit, rather than the head of the chunk: the answer to a
 * specific question is usually in the middle of a section, and leading with the
 * section's preamble wastes the agent's context on boilerplate.
 */
function snippet(chunk: Chunk, terms: Map<string, number>): string {
    const words = chunk.content.split(/\s+/).filter((w) => w.length > 0);
    if (words.length <= SNIPPET_TOKENS) return chunk.content.trim();

    let hit = -1;
    outer: for (let i = 0; i < words.length; i += 1) {
        const normalized = words[i].toLowerCase().replace(/[^a-z0-9_]/g, "");
        if (!normalized) continue;
        for (const term of terms.keys()) {
            if (normalized.includes(term)) {
                hit = i;
                break outer;
            }
        }
    }

    // Bias the window to start slightly before the hit so the sentence that
    // introduces it survives.
    const start = hit < 0 ? 0 : Math.max(0, hit - 40);
    const end = Math.min(words.length, start + SNIPPET_TOKENS);
    const body = words.slice(start, end).join(" ");
    return (start > 0 ? "... " : "") + body + (end < words.length ? " ..." : "");
}

function fullContent(chunk: Chunk): string {
    if (chunk.content.length <= MAX_FULL_CHARS) return chunk.content;
    return (
        chunk.content.slice(0, MAX_FULL_CHARS) +
        "\n\n[truncated at " + MAX_FULL_CHARS + " characters - request a narrower section with qail_doc { path, section }]"
    );
}

function footer(extra?: string): string {
    const bits = [
        "qail " + qailVersion(),
        CHUNKS.length + " chunks indexed",
    ];
    if (!INDEX_USABLE) bits.push("DEGRADED: BM25 index out of sync with corpus, using literal matching");
    if (extra) bits.push(extra);
    return "\n---\n" + bits.join(" | ") +
        "\nLegacy paren schema syntax `table t ( ... )` is excluded from all results; QAIL schemas use the brace dialect.";
}

