/* Tool: qail_doc                                                             */
/* -------------------------------------------------------------------------- */

/**
 * Path matching is deliberately forgiving. Agents cite documents by basename
 * ("quickstart.md") far more often than by the full repo-relative path, and a
 * strict match would turn a recoverable near-miss into a dead end.
 */
function resolvePath(path: string): number[] {
    const wanted = path.toLowerCase().replace(/^\.?\//, "");
    const exact = VISIBLE.filter((i) => CHUNKS[i].path.toLowerCase() === wanted);
    if (exact.length) return exact;

    const suffix = VISIBLE.filter((i) => CHUNKS[i].path.toLowerCase().endsWith(wanted));
    if (suffix.length) return suffix;

    return VISIBLE.filter((i) => CHUNKS[i].path.toLowerCase().includes(wanted));
}

function toolDoc(args: any): unknown {
    const id = typeof args?.id === "string" ? args.id.trim() : "";
    const path = typeof args?.path === "string" ? args.path.trim() : "";
    const section = typeof args?.section === "string" ? args.section.trim().toLowerCase() : "";
    const outline = args?.outline === true;

    if (!id && !path) {
        return toolError(
            "qail_doc needs either `id` (from a qail_search result) or `path` (a repo-relative doc path, e.g. \"docs/src/reference/queries.md\").\n" +
            "To discover either: call qail_search, or qail_map for the documentation tree.",
        );
    }

    let indices: number[];
    let label: string;

    if (id) {
        indices = VISIBLE.filter((i) => CHUNKS[i].id === id);
        label = "id " + id;
        if (indices.length === 0) {
            const known = CHUNKS.some((c) => c.id === id);
            return toolError(
                known
                    ? "Chunk " + id + " exists but teaches the legacy paren schema dialect and is intentionally not served. Use qail://core/schema-reference for the current brace dialect."
                    : "No chunk with id " + id + ". Ids come from qail_search results and are not guessable; run qail_search first.",
            );
        }
    } else {
        indices = resolvePath(path);
        label = "path " + path;
        if (indices.length === 0) {
            return toolError(
                "No document matched path " + path + ". Paths are repo-relative (\"docs/src/...\", \"core/README.md\"). " +
                "Call qail_map for the documentation tree or qail_search to locate the topic.",
            );
        }
    }

    if (section) {
        const narrowed = indices.filter((i) => {
            const chunk = CHUNKS[i];
            const hay = (chunk.title + " " + (chunk.headingPath ?? []).join(" ")).toLowerCase();
            return hay.includes(section);
        });
        if (narrowed.length === 0) {
            const available = indices
                .map((i) => CHUNKS[i].title)
                .filter((t, n, all) => all.indexOf(t) === n)
                .slice(0, 40);
            return toolError(
                "No section matching \"" + section + "\" in " + label + ". Sections present: " + available.join(" | "),
            );
        }
        indices = narrowed;
    }

    // Preserve corpus order so a multi-chunk document reads top to bottom.
    indices.sort((a, b) => a - b);

    if (outline) {
        const lines: string[] = ["# Outline: " + label, ""];
        let totalTokens = 0;

        // A basename like "quickstart.md" can resolve to more than one file.
        // Interleaving their headings by corpus order produces an outline that
        // reads as one incoherent document, so group under an explicit path.
        const paths = [...new Set(indices.map((i) => CHUNKS[i].path))];
        for (const path of paths) {
            if (paths.length > 1) lines.push("## " + path);
            for (const i of indices.filter((n) => CHUNKS[n].path === path)) {
                const chunk = CHUNKS[i];
                const depth = (chunk.headingPath ?? []).length;
                totalTokens += chunk.tokens;
                lines.push(
                    "  ".repeat(depth) + "- " + chunk.title +
                    "  (" + chunk.tokens + " tokens, id: " + chunk.id + ")",
                );
            }
            if (paths.length > 1) lines.push("");
        }
        lines.push("");
        lines.push(
            indices.length + " chunk" + (indices.length === 1 ? "" : "s") +
            (paths.length > 1 ? " across " + paths.length + " files" : "") +
            ", " + totalTokens + " tokens total.",
        );
        lines.push("Fetch one with qail_doc { \"id\": \"<id>\" }, or a subtree with qail_doc { \"path\": \"...\", \"section\": \"<heading>\" }.");
        return toolText(lines.join("\n") + footer());
    }

    const lines: string[] = [];
    for (const i of indices) {
        const chunk = CHUNKS[i];
        lines.push("# " + chunk.title);
        lines.push("id: " + chunk.id + " | path: " + locationOf(chunk) + " | kind: " + chunk.kind + " | area: " + chunk.area);
        lines.push("");
        lines.push(fullContent(chunk));
        lines.push("");
    }

    // A whole-document fetch can be enormous; nudge toward the outline instead.
    const tokens = indices.reduce((sum, i) => sum + CHUNKS[i].tokens, 0);
    const hint = tokens > 6000
        ? "This document is " + tokens + " tokens. Next time call qail_doc { \"outline\": true } first and fetch only the section you need."
        : undefined;

    return toolText(lines.join("\n") + footer(hint));
}

