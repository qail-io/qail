function toolExamples(args: any): unknown {
    const query = typeof args?.query === "string" ? args.query.trim() : "";
    const construct = typeof args?.construct === "string" ? args.construct.trim() : "";
    const polarityRaw = typeof args?.polarity === "string" ? args.polarity.toLowerCase() : "valid";
    const polarity = ["valid", "invalid", "both"].includes(polarityRaw) ? polarityRaw : "valid";
    const limit = clampInt(args?.limit, 5, 1, 20);

    const validKinds = [...KINDS.keys()].filter((k) => isExampleKind(k));
    const invalidKinds = [...KINDS.keys()].filter((k) => isInvalidKind(k));

    const sections: string[] = [];

    const collect = (kinds: string[], want: number): number[] => {
        if (kinds.length === 0 || want <= 0) return [];
        if (query) return search(query, { kind: kinds }, want).map((h) => h.idx);
        if (construct) {
            const picked = examplesForConstruct(normalizeConstruct(construct), want).filter((i) =>
                kinds.includes(CHUNKS[i].kind),
            );
            if (picked.length) return picked;
            // examplesForConstruct only ranks positive examples; for the
            // negative corpus fall through to a plain construct search.
            return search(construct, { kind: kinds }, want).map((h) => h.idx);
        }
        return VISIBLE.filter((i) => kinds.includes(CHUNKS[i].kind)).slice(0, want);
    };

    if (polarity === "valid" || polarity === "both") {
        const hits = collect(validKinds, limit);
        sections.push("## Verified examples (parsed and transpiled by the real pipeline)");
        sections.push(
            hits.length
                ? hits.map((i) => CHUNKS[i].content.trim() + "\n(id: " + CHUNKS[i].id + ")").join("\n\n")
                : "No verified example matched. Every example in this corpus was executed, so the set is exact rather than exhaustive — verify a candidate with qail_parse_query.",
        );
    }

    if (polarity === "invalid" || polarity === "both") {
        const hits = collect(invalidKinds, limit);
        sections.push("## Negative examples (real parser / transpiler output)");
        sections.push(
            hits.length
                ? hits.map((i) => CHUNKS[i].content.trim() + "\n(id: " + CHUNKS[i].id + ")").join("\n\n")
                : "No negative example matched. The negative corpus is small and covers specific known traps only.",
        );
    }

    const header = "# qail_examples" +
        (query ? ": " + query : "") +
        (construct ? " [construct: " + construct + "]" : "") +
        " [polarity: " + polarity + "]";

    return toolText(header + "\n\n" + sections.join("\n\n") + footer());
}

