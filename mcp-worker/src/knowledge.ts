function productionIndices(): number[] {
    return VISIBLE.filter((i) => CHUNKS[i].kind === "production");
}

function toolSyntax(args: any): unknown {
    const requested = typeof args?.construct === "string" ? args.construct.trim() : "";
    const wantExamples = clampInt(args?.examples, 3, 0, 10);
    const productions = productionIndices();

    if (!requested) {
        const byConstruct = new Map<string, number>();
        for (const i of productions) {
            const key = constructOf(CHUNKS[i]);
            byConstruct.set(key, (byConstruct.get(key) ?? 0) + 1);
        }
        const names = [...byConstruct.keys()].sort();
        const lines = [
            "# QAIL grammar constructs (" + names.length + ")",
            "",
            "Actions: get (SELECT), add (INSERT), set (UPDATE), del (DELETE), merge (MERGE).",
            "Also: with (CTE), export, and begin / commit / rollback for transactions.",
            "",
            "Call qail_syntax { \"construct\": \"<name>\" } for the grammar card and verified examples.",
            "SQL names work too: \"select\", \"insert\", \"on conflict\" are aliased onto the QAIL keyword.",
            "",
        ];
        for (const name of names) {
            const count = byConstruct.get(name) ?? 0;
            lines.push("- " + name + (count > 1 ? "  (" + count + " productions)" : ""));
        }
        return toolText(lines.join("\n") + footer());
    }

    const candidates = normalizeConstruct(requested);
    const matched: number[] = [];
    for (const i of productions) {
        const key = constructOf(CHUNKS[i]);
        if (candidates.some((c) => constructMatches(key, c))) matched.push(i);
    }

    if (matched.length === 0) {
        // Fall back to retrieval rather than a bare "not found": the agent's
        // word for the construct may simply not be in the alias map.
        const fallback = search(requested, { kind: ["production"] }, 5);
        if (fallback.length === 0) {
            return toolError(
                "No grammar construct matched \"" + requested + "\". " +
                "Call qail_syntax with no arguments to list every construct.",
            );
        }
        matched.push(...fallback.map((h) => h.idx));
    }

    // Exact construct matches first; partials afterwards.
    matched.sort((a, b) => {
        const rank = (i: number) => (candidates.includes(constructOf(CHUNKS[i])) ? 0 : 1);
        return rank(a) - rank(b) || a - b;
    });

    const lines: string[] = ["# Syntax: " + requested, ""];
    for (const i of matched.slice(0, 8)) {
        const chunk = CHUNKS[i];
        lines.push("## " + chunk.title + "  (construct: " + constructOf(chunk) + ")");
        lines.push("source: " + chunk.path + " | id: " + chunk.id);
        lines.push("");
        lines.push(fullContent(chunk));
        lines.push("");
    }

    if (wantExamples > 0) {
        const examples = examplesForConstruct(candidates, wantExamples);
        lines.push("## Verified examples");
        if (examples.length === 0) {
            lines.push(
                "None of the verified examples exercise this construct. " +
                "Every example in the corpus was actually run through the parser and transpiler, so absence means untested here, not unsupported. " +
                "Confirm a candidate snippet with qail_parse_query.",
            );
        } else {
            for (const i of examples) {
                lines.push("");
                lines.push(CHUNKS[i].content.trim());
            }
        }
        lines.push("");
    }

    return toolText(lines.join("\n") + footer());
}

/**
 * Rank verified examples for a construct: an example whose QAIL input *starts*
 * with the construct demonstrates it; one that merely mentions it somewhere is
 * a weaker illustration.
 */
function examplesForConstruct(candidates: string[], limit: number): number[] {
    const scored: { idx: number; rank: number }[] = [];
    for (const i of VISIBLE) {
        if (!isExampleKind(CHUNKS[i].kind)) continue;
        const input = exampleInput(CHUNKS[i]).toLowerCase();
        if (!input) continue;

        let rank = 0;
        for (const c of candidates) {
            const word = c.replace(/_/g, " ");
            if (input.startsWith(c) || input.startsWith(word)) {
                rank = Math.max(rank, 2);
            } else if (input.includes(c) || input.includes(word)) {
                rank = Math.max(rank, 1);
            }
        }
        if (rank > 0) scored.push({ idx: i, rank });
    }
    // Shortest first within a rank. The corpus contains both "get users" and a
    // comment-escaping torture case for the same construct; the agent should be
    // shown the canonical form before the edge case.
    scored.sort((a, b) => b.rank - a.rank || CHUNKS[a.idx].tokens - CHUNKS[b.idx].tokens || a.idx - b.idx);
    return scored.slice(0, limit).map((s) => s.idx);
}

