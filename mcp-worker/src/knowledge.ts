function toolText(text: string): unknown {
    return { content: [{ type: "text", text }], isError: false };
}

function toolError(message: string): unknown {
    return { content: [{ type: "text", text: message }], isError: true };
}

/* -------------------------------------------------------------------------- */
/* Corpus accessors                                                           */
/* -------------------------------------------------------------------------- */

function distinct(pick: (c: Chunk) => string): Map<string, number> {
    const counts = new Map<string, number>();
    for (const idx of VISIBLE) {
        const key = pick(CHUNKS[idx]);
        if (!key) continue;
        counts.set(key, (counts.get(key) ?? 0) + 1);
    }
    return counts;
}

const KINDS = distinct((c) => c.kind);
const AREAS = distinct((c) => c.area);

/** Kind names holding negative examples: inputs that fail, with the real error. */
function isInvalidKind(kind: string): boolean {
    return /invalid|negative|counter/i.test(kind);
}

/**
 * Only the executed QAIL-to-SQL pairs count as examples here.
 *
 * "example-code" is deliberately excluded: those chunks are Rust source from
 * core/examples/*.rs. They are excellent search results and useless as answers
 * to "show me a query", because an agent shown Rust when it asked for QAIL will
 * cheerfully write Rust.
 */
function isExampleKind(kind: string): boolean {
    return kind === "example";
}

/**
 * Grammar chunks name their production (`parse_where_clause`), but agents ask
 * for the construct (`where`). The exporter emits the construct in the chunk
 * body; fall back to deriving it from the production name so a schema tweak
 * upstream degrades instead of breaking.
 */
function constructOf(chunk: Chunk): string {
    const declared = /(?:^|\n)\s*(?:[-*]\s*)?construct:\s*([a-z0-9_]+)/i.exec(chunk.content);
    if (declared) return declared[1].toLowerCase();

    return chunk.title
        .toLowerCase()
        .trim()
        .replace(/^parse_/, "")
        .replace(/_(clause|command|strict)$/, "");
}

/**
 * The first QAIL line of an example chunk. Used to decide whether an example
 * "starts with" a construct, which is a much stronger signal than the construct
 * merely appearing somewhere in the body.
 */
function exampleInput(chunk: Chunk): string {
    const labelled = /(?:^|\n)\s*(?:input|qail):\s*(.+)/i.exec(chunk.content);
    if (labelled) return labelled[1].trim().replace(/^`|`$/g, "");

    for (const line of chunk.content.split("\n")) {
        const trimmed = line.trim().replace(/^`+|`+$/g, "");
        if (!trimmed) continue;
        if (trimmed.startsWith("#") || trimmed.startsWith("```")) continue;
        return trimmed;
    }
    return "";
}

/**
 * Resolve a user-supplied construct name into the candidate keys to match on.
 *
 * "on conflict" must reach the `on_conflict` production, and so must "conflict"
 * on its own, so the leading SQL filler word is stripped as a second candidate.
 */
function normalizeConstruct(name: string): string[] {
    const lowered = name.toLowerCase().trim().replace(/[^a-z0-9_ ]/g, "").replace(/\s+/g, "_");
    const out = new Set<string>();
    if (lowered) out.add(lowered);

    for (const alias of ALIASES[lowered] ?? ALIASES[lowered.replace(/_/g, " ")] ?? []) {
        out.add(alias);
    }

    const segments = lowered.split("_").filter((p) => p.length > 1);
    const meaningful = segments.filter((p) => !STOPWORDS.has(p));
    if (meaningful.length && meaningful.length < segments.length) {
        out.add(meaningful.join("_"));
        out.add(meaningful[meaningful.length - 1]);
    }

    return [...out];
}

/**
 * Segment-aware construct matching.
 *
 * Plain substring matching is wrong here and quietly so: `"merge_after_target"`
 * contains `"get"`, so asking for the `get` action used to return the MERGE
 * grammar. Matching whole underscore-separated segments keeps `conflict` ->
 * `on_conflict` and `join` -> `join_condition` working without that class of
 * accident.
 */
function constructMatches(key: string, candidate: string): boolean {
    if (key === candidate) return true;
    const keyParts = key.split("_");
    const candParts = candidate.split("_");
    if (candParts.every((p) => keyParts.includes(p))) return true;
    if (keyParts.every((p) => candParts.includes(p))) return true;
    return false;
}

