/* Tool: qail_search                                                          */
/* -------------------------------------------------------------------------- */

function toolSearch(args: any): unknown {
    const query = typeof args?.query === "string" ? args.query.trim() : "";
    if (!query) {
        return toolError("qail_search requires a non-empty `query`. Example: { \"query\": \"how do I write an upsert\" }");
    }

    const limit = clampInt(args?.limit, 5, 1, 20);
    const snippetsOnly = args?.snippetsOnly !== false;
    const filter: SearchFilter = {
        kind: stringArray(args?.kind),
        area: stringArray(args?.area),
    };

    const unknownKinds = (filter.kind ?? []).filter((k) => !KINDS.has(k));
    const unknownAreas = (filter.area ?? []).filter((a) => !AREAS.has(a));

    const terms = expandQuery(query);
    const hits = search(query, filter, limit);

    if (hits.length === 0) {
        const notes: string[] = ["No matches for: " + query];
        if (unknownKinds.length) {
            notes.push("Unknown kind filter(s): " + unknownKinds.join(", ") + ". Available: " + [...KINDS.keys()].sort().join(", "));
        }
        if (unknownAreas.length) {
            notes.push("Unknown area filter(s): " + unknownAreas.join(", ") + ". Available: " + [...AREAS.keys()].sort().join(", "));
        }
        notes.push("Try qail_map for the repo layout, or qail_syntax with no arguments to list every grammar construct.");
        return toolText(notes.join("\n") + footer());
    }

    const lines: string[] = ["# qail_search: " + query, ""];
    hits.forEach((hit, rank) => {
        const chunk = CHUNKS[hit.idx];
        lines.push("## " + (rank + 1) + ". " + chunk.title);
        lines.push(
            "id: " + chunk.id +
            " | path: " + locationOf(chunk) +
            " | kind: " + chunk.kind +
            " | area: " + chunk.area +
            " | " + chunk.tokens + " tokens" +
            " | score " + hit.score.toFixed(2),
        );
        lines.push("");
        lines.push(snippetsOnly ? snippet(chunk, terms) : fullContent(chunk));
        lines.push("");
    });

    if (snippetsOnly) {
        lines.push("Fetch any result in full with qail_doc { \"id\": \"<id>\" }.");
    }

    return toolText(lines.join("\n") + footer());
}

