/**
 * Documentation-retrieval layer for the QAIL MCP server.
 *
 * The six WASM tools answer questions about a snippet the agent already has
 * ("parse this", "transpile that"). They cannot answer "how do I write an
 * upsert" or "what does the schema DSL look like", because the answer lives in
 * prose the agent has never seen. This module closes that gap: it ships the
 * repo's documentation as a pre-chunked, pre-indexed bundle and exposes it as
 * five retrieval tools plus three always-loadable orientation resources.
 *
 * Everything here is pure and synchronous. The corpus and the BM25 index are
 * JSON imports, so they are baked into the Worker bundle at build time — there
 * is no KV lookup, no network call, and no cold-start I/O, which matters
 * because Workers forbids async work in global scope and every millisecond
 * here is billed CPU.
 *
 * The corpus and index are produced by `core/examples/knowledge_export.rs` plus
 * the corpus builder; this file only reads them. If their schema changes, the
 * accessors at the top of this file are the only place that needs to follow.
 */

// The version string comes from the WASM module so search footers can never
// drift from the parser that actually answers qail_parse_query. It is read
// lazily inside request handling: `initSync` runs in index.ts module scope, and
// calling into WASM before that would touch uninitialised memory.
import { version } from "./wasm/qail_wasm.js";

import corpusJson from "./knowledge/corpus.json";
import indexJson from "./knowledge/index.json";

/* -------------------------------------------------------------------------- */
/* Corpus shape                                                               */
/* -------------------------------------------------------------------------- */

interface Chunk {
    /** Stable retrieval handle, quoted in every result so qail_doc can fetch it. */
    id: string;
    /** Repo-relative source path, e.g. "docs/src/reference/queries.md". */
    path: string;
    /**
     * One of the eight kinds the builder emits:
     * "guide" | "production" | "example-code" | "example" | "crate-readme"
     * | "sdk-readme" | "schema-sample" | "negative".
     */
    kind: string;
    /** Coarse subsystem bucket, e.g. "core", "gateway", "sdk", "grammar". */
    area: string;
    title: string;
    /** Ancestor headings, outermost first. Empty for non-markdown chunks. */
    headingPath: string[];
    content: string;
    tokens: number;
    /** Editorial boost. Verified examples outrank prose; changelogs are excluded upstream. */
    weight: number;
    /**
     * Schema dialect this chunk teaches, when it teaches one.
     * "paren" marks the LEGACY `table users ( ... )` syntax parsed only by
     * core/src/parser/schema.rs. It is filtered out of every result below,
     * unconditionally — an agent that learns it will write schemas that the
     * migration and codegen parsers both reject.
     */
    dialect: string | null;
}

interface Bm25Index {
    /** term -> number of chunks containing it. */
    df: Record<string, number>;
    /** term -> [chunkIndex, termFrequency][]. */
    postings: Record<string, [number, number][]>;
    /** Token length per chunk, parallel to the corpus array. */
    len: number[];
    avgLen: number;
    /** Corpus size the index was built against. */
    n: number;
}

const CHUNKS = (corpusJson as unknown as Chunk[]) ?? [];
const INDEX = indexJson as unknown as Bm25Index;

/**
 * The builder creates these maps with Object.create(null), but a null prototype
 * does not survive JSON serialisation: after the import they are ordinary
 * objects, so `POSTINGS[term]` for a term like "constructor" or "toString" would
 * walk the prototype chain and hand back a function that passes a truthy guard
 * and then throws when destructured. Rehydrate the null prototype once, here, so
 * every lookup below is an own-property read by construction.
 */
const POSTINGS: Record<string, [number, number][]> = Object.assign(
    Object.create(null) as Record<string, [number, number][]>,
    INDEX?.postings ?? {},
);
const DF: Record<string, number> = Object.assign(
    Object.create(null) as Record<string, number>,
    INDEX?.df ?? {},
);

/**
 * The corpus and the index are generated by a separate build step. If they ever
 * disagree — a stale index, a partial regeneration — BM25 would silently score
 * against the wrong documents. Detect that once, at module scope, and fall back
 * to a literal scorer rather than returning confidently wrong results.
 */
const INDEX_USABLE =
    !!INDEX &&
    !!INDEX.postings &&
    !!INDEX.df &&
    Array.isArray(INDEX.len) &&
    INDEX.len.length === CHUNKS.length &&
    INDEX.avgLen > 0;

/** Chunks the agent is allowed to see, as indices into CHUNKS. */
const VISIBLE: number[] = CHUNKS.map((_, i) => i).filter((i) => CHUNKS[i].dialect !== "paren");
const VISIBLE_SET = new Set(VISIBLE);

function qailVersion(): string {
    try {
        return version();
    } catch {
        // Reached only if a caller invokes a knowledge tool before initSync,
        // which the Worker's control flow makes impossible. Degrade rather than
        // fail a request over a footer string.
        return "unknown";
    }
}

/* -------------------------------------------------------------------------- */
/* Tokenisation and query expansion                                           */
/* -------------------------------------------------------------------------- */

/**
 * Must match the tokeniser that built index.json, which was verified against
 * the shipped vocabulary: lowercase, split on every non-alphanumeric character
 * (underscores included, so `parse_where_clause` indexes as parse/clause), drop
 * anything shorter than two characters, drop stopwords.
 *
 * Asymmetric on stemming, deliberately. The BUILDER indexes each token and, for
 * plurals, its singular stem as well, so the vocabulary holds both `fields` and
 * `field`. Queries are NOT stemmed here: a query term is looked up as written
 * and finds its own posting list either way, while stemming the query too would
 * collapse distinct QAIL keywords (`set` into `sets`). The index is a superset
 * of the text; chunk lengths in index.json count only the unstemmed tokens, so
 * the stems do not distort BM25 length normalisation.
 *
 * A query term missing from the index simply scores nothing, so an
 * over-inclusive stopword list is the only way to actually lose signal. Every
 * word below was checked against the shipped vocabulary and is absent from it;
 * `use` and `using` were removed after the check because the index does keep
 * them, and `using` is load-bearing in MERGE syntax.
 *
 * The list still earns its place: the literal fallback scorer and the snippet
 * window both use these terms, and there a match on "the" is pure noise.
 */
const STOPWORDS = new Set([
    "a", "an", "and", "are", "as", "at", "be", "but", "by", "can", "do", "does",
    "for", "from", "has", "have", "how", "i", "if", "in", "into", "is", "it",
    "its", "me", "my", "no", "not", "of", "on", "or", "should", "so", "than",
    "that", "the", "their", "them", "then", "there", "these", "they", "this",
    "to", "was", "what", "when", "where", "which", "will", "with", "would",
    "you", "your",

    // Instructional filler. These carry no intent in a question but are real,
    // reasonably rare terms in the prose, so an unfiltered "how do I write an
    // upsert" ranks every page that happens to discuss writes above the actual
    // conflict documentation. Measured against the shipped corpus.
    "write", "writes", "writing", "wrote", "want", "wants", "need", "needs",
    "please", "tell", "explain", "way", "thing", "things", "doing",
]);

function tokenize(text: string): string[] {
    const out: string[] = [];
    for (const raw of text.toLowerCase().split(/[^a-z0-9]+/)) {
        if (raw.length < 2) continue;
        if (STOPWORDS.has(raw)) continue;
        out.push(raw);
    }
    return out;
}

/**
 * Agents arrive thinking in SQL. Someone searching "insert on conflict" must
 * land on the `add` / `conflict` documentation even though neither word appears
 * in their query, so the query is expanded through this map before scoring.
 *
 * Two QAIL keywords are deliberately absent as expansion *targets*: `where` and
 * `with`. Both are English stopwords, so the index generator dropped them from
 * the vocabulary and expanding to them would score exactly zero. Queries about
 * those constructs are routed to the words that were indexed instead
 * (`condition`, `clause`, `cte`), which is why the right-hand sides below are
 * not simply the QAIL keyword in every case.
 */
const ALIASES: Record<string, string[]> = Object.assign(Object.create(null) as Record<string, string[]>, {
    // Actions. get/add/set/del/merge are the five DML verbs.
    select: ["get"],
    query: ["get"],
    read: ["get"],
    fetch: ["get"],
    insert: ["add"],
    create: ["add"],
    update: ["set"],
    modify: ["set"],
    delete: ["del"],
    remove: ["del"],
    drop: ["del"],
    upsert: ["conflict", "add"],
    conflict: ["conflict", "add"],
    merge: ["merge"],

    // Clauses. `with` is unindexed, so CTE questions route through "cte".
    join: ["join"],
    joins: ["join"],
    cte: ["cte", "recursive"],
    recursive: ["recursive", "cte"],
    subquery: ["subquery", "cte"],
    order: ["order", "sort"],
    sort: ["order"],
    sorting: ["order"],
    group: ["group", "having"],
    aggregate: ["group", "having"],
    limit: ["limit", "offset"],
    paginate: ["limit", "offset"],
    pagination: ["limit", "offset"],
    // `where` is unindexed; "condition"/"filter"/"clause" carry these queries.
    filter: ["filter", "condition"],
    filtering: ["filter", "condition"],
    predicate: ["condition", "filter"],
    condition: ["condition", "filter"],
    column: ["fields", "column"],
    columns: ["fields", "column"],
    projection: ["fields"],
    row: ["values"],
    rows: ["values"],

    // Schema and platform.
    table: ["table", "schema"],
    schema: ["schema", "table"],
    migration: ["migrate", "migration"],
    migrations: ["migrate", "migration"],
    ddl: ["migration", "table"],
    rls: ["rls", "policy"],
    policy: ["policy", "rls"],
    tenant: ["rls", "policy", "tenant"],
    auth: ["auth", "policy"],
    index: ["index"],
    transaction: ["begin", "commit", "rollback"],
    param: ["param"],
    params: ["param"],
    binding: ["param"],
    placeholder: ["param"],
    codegen: ["codegen", "typed"],
});

/**
 * Multi-word aliases, checked against the raw query before tokenisation
 * because tokenising destroys adjacency. Targets are single indexed tokens:
 * the index splits on underscores too, so "primary_key" is not a term and
 * expanding to it would match nothing.
 */
const PHRASE_ALIASES: [string, string[]][] = [
    ["on conflict", ["conflict", "add"]],
    ["order by", ["order"]],
    ["group by", ["group", "having"]],
    ["inner join", ["join", "inner"]],
    ["left join", ["join", "left"]],
    ["common table expression", ["cte", "recursive"]],
    ["row level security", ["rls", "policy"]],
    ["foreign key", ["references", "foreign"]],
    ["primary key", ["primary", "key"]],
    ["not null", ["null", "column"]],
    ["prepared statement", ["param", "prepared"]],
    ["where clause", ["condition", "clause", "filter"]],
];

/**
 * Expanded terms carry less weight than what the user actually typed, so an
 * alias can surface a document but cannot outrank a literal match.
 */
const EXPANSION_WEIGHT = 0.6;

/** Query terms with per-term weights, literal terms at 1.0. */
function expandQuery(query: string): Map<string, number> {
    const weighted = new Map<string, number>();
    const bump = (term: string, w: number) => {
        weighted.set(term, Math.max(weighted.get(term) ?? 0, w));
    };

    for (const term of tokenize(query)) bump(term, 1);

    const lowered = query.toLowerCase();
    for (const [phrase, targets] of PHRASE_ALIASES) {
        if (lowered.includes(phrase)) {
            for (const t of targets) bump(t, EXPANSION_WEIGHT);
        }
    }

    for (const term of tokenize(query)) {
        for (const t of ALIASES[term] ?? []) bump(t, EXPANSION_WEIGHT);
    }

    return weighted;
}

/* -------------------------------------------------------------------------- */
/* Scoring                                                                    */
/* -------------------------------------------------------------------------- */

const K1 = 1.2;
const B = 0.75;

interface Hit {
    idx: number;
    score: number;
}

interface SearchFilter {
    kind?: string[];
    area?: string[];
}

function passesFilter(idx: number, filter: SearchFilter): boolean {
    if (!VISIBLE_SET.has(idx)) return false;
    const chunk = CHUNKS[idx];
    if (filter.kind && filter.kind.length && !filter.kind.includes(chunk.kind)) return false;
    if (filter.area && filter.area.length && !filter.area.includes(chunk.area)) return false;
    return true;
}

/**
 * Okapi BM25, with each chunk's final score multiplied by its editorial weight
 * so a verified example beats a passing mention in prose at equal relevance.
 */
function scoreBm25(terms: Map<string, number>, filter: SearchFilter): Hit[] {
    const totals = new Map<number, number>();
    const n = INDEX.n || CHUNKS.length;

    for (const [term, termWeight] of terms) {
        const postings = POSTINGS[term];
        if (!postings) continue;

        const df = DF[term] ?? postings.length;
        // +1 inside the log keeps the idf non-negative for terms that appear in
        // more than half the corpus; a bare Robertson idf would go negative and
        // penalise documents for containing a common keyword like "get".
        const idf = Math.log(1 + (n - df + 0.5) / (df + 0.5));

        for (const [idx, tf] of postings) {
            if (!passesFilter(idx, filter)) continue;
            const len = INDEX.len[idx] || CHUNKS[idx].tokens || INDEX.avgLen;
            const norm = tf + K1 * (1 - B + (B * len) / INDEX.avgLen);
            const contribution = (idf * (tf * (K1 + 1))) / norm;
            totals.set(idx, (totals.get(idx) ?? 0) + contribution * termWeight);
        }
    }

    const hits: Hit[] = [];
    for (const [idx, raw] of totals) {
        hits.push({ idx, score: raw * (CHUNKS[idx].weight ?? 1) });
    }
    return hits;
}

/**
 * Fallback used when the index does not match the corpus. Substring counting is
 * far worse than BM25, but it is honest and keeps the server useful instead of
 * returning nothing after a partial regeneration.
 */
function scoreLiteral(terms: Map<string, number>, filter: SearchFilter): Hit[] {
    const hits: Hit[] = [];
    for (const idx of VISIBLE) {
        if (!passesFilter(idx, filter)) continue;
        const chunk = CHUNKS[idx];
        const haystack = (chunk.title + "\n" + chunk.content).toLowerCase();
        let score = 0;
        for (const [term, termWeight] of terms) {
            let from = 0;
            let count = 0;
            for (;;) {
                const at = haystack.indexOf(term, from);
                if (at === -1) break;
                count += 1;
                from = at + term.length;
                if (count > 20) break;
            }
            if (count) score += termWeight * (1 + Math.log(count));
        }
        if (score > 0) hits.push({ idx, score: score * (chunk.weight ?? 1) });
    }
    return hits;
}

function search(query: string, filter: SearchFilter, limit: number): Hit[] {
    const terms = expandQuery(query);
    if (terms.size === 0) return [];
    const hits = INDEX_USABLE ? scoreBm25(terms, filter) : scoreLiteral(terms, filter);
    hits.sort((a, b) => b.score - a.score || a.idx - b.idx);
    return hits.slice(0, limit);
}

