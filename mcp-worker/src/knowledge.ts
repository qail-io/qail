export function isKnowledgeTool(name: string): boolean {
    return TOOL_NAMES.has(name);
}

export function callKnowledgeTool(name: string, args: any): unknown {
    // Defensive: a malformed chunk or a corpus/index mismatch should surface as
    // an MCP tool error, never as a 500 from the Worker. The WASM tools cannot
    // throw; these must not either, or clients see two different failure modes
    // for the same endpoint.
    try {
        switch (name) {
            case "qail_search":
                return toolSearch(args ?? {});
            case "qail_doc":
                return toolDoc(args ?? {});
            case "qail_syntax":
                return toolSyntax(args ?? {});
            case "qail_examples":
                return toolExamples(args ?? {});
            case "qail_map":
                return toolMap(args ?? {});
            default:
                return toolError("Unknown knowledge tool: " + name);
        }
    } catch (err) {
        return toolError("Knowledge tool " + name + " failed: " + err);
    }
}

export function readKnowledgeResource(uri: string): string | null {
    return RESOURCE_BODIES[uri] ?? null;
}
